// One-off generator: reads all presets from scripts/presets-src/*.cu and writes
// src/lib/presets.js.  Run:  node scripts/gen-presets.cjs     Verify:  node scripts/test-presets.cjs
const fs = require('fs');
const path = require('path');

const src = (n) =>
  fs.readFileSync(path.join(__dirname, 'presets-src', n + '.cu'), 'utf8').replace(/\r\n/g, '\n').trimEnd();

// id, title, blurb, tag, devices, expected stdout substring (null = deliberate bug, must throw/catch), code
const entries = [
  ['vector_add', 'Vector Addition', 'Grid / block indexing and host-device copies', 'Basics', 1, 'h_c[10]  = 30.000000', src('vector_add')],
  ['saxpy', 'SAXPY', 'a*x + y, the NVIDIA cuda-samples classic', 'Basics', 1, 'y[0] = 5.000000', src('saxpy')],
  ['relu', 'ReLU Activation', 'Deep-learning elementwise primitive', 'ML', 1, 'out[63] = 31.000000', src('relu')],
  ['matmul_shared', 'Tiled MatMul', '__shared__ tiling with __syncthreads()', 'Memory', 1, 'C[0,0] = 64.000000', src('matmul_shared')],
  ['warp_reduction', 'Warp Reduction', '__shfl_down_sync lockstep warp primitives', 'Warp', 1, 'result = 32.000000', src('warp_reduction')],
  ['atomic_histogram', 'Atomic Histogram', 'atomicAdd and contention telemetry', 'Atomics', 1, 'Bin 0: count = 32', src('atomic_histogram')],
  ['multi_gpu_nccl', 'Multi-GPU AllReduce', 'Ring ncclAllReduce across 4 virtual GPUs', 'Multi-GPU', 4, 'GPU 3 reduced element 0: 4.000000', src('multi_gpu_nccl')],
  ['bug_oob', 'Bug: Out-of-Bounds', 'A missing bounds guard is caught with thread and block', 'Debugging', 1, null, src('bug_oob')],
  ['bug_barrier', 'Bug: Divergent Barrier', 'A __syncthreads() deadlock caught before hardware', 'Debugging', 1, null, src('bug_barrier')]
];

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const q = (s) => JSON.stringify(s);

let out = `// Playground presets. Generated by scripts/gen-presets.cjs and verified by scripts/test-presets.cjs.
// devices = recommended virtual cluster size, expect = stdout substring asserted by the test
// (null = the preset is a deliberate bug and must produce a diagnostic instead).
export const PRESETS = [
`;
for (const [id, title, blurb, tag, devices, expect, code] of entries) {
  out += `  {
    id: ${q(id)},
    title: ${q(title)},
    blurb: ${q(blurb)},
    tag: ${q(tag)},
    devices: ${devices},
    expect: ${expect === null ? 'null' : q(expect)},
    code: \`${esc(code)}\`
  },
`;
}
out = out.replace(/,\n$/, '\n') + `];

export const DEFAULT_PRESET = 'vector_add';
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'presets.js'), out);
console.log('presets.js written with', entries.length, 'presets');
