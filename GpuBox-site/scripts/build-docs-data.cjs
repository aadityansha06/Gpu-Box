// scripts/build-docs-data.cjs
// Reads markdown documentation files from ../docs and ../README.md,
// compiles them with marked, and emits src/lib/docs-data.js.
const fs = require('fs');
const path = require('path');
const { marked } = require('marked');

// Configure marked
marked.setOptions({
  gfm: true,
  breaks: false
});

const docsDir = path.resolve(__dirname, '../../docs');
const rootDir = path.resolve(__dirname, '../..');

const DOC_FILES = [
  {
    slug: 'overview',
    title: 'Overview & Quickstart',
    category: 'Getting Started',
    filePath: path.join(docsDir, 'USAGE.md'),
    summary: 'Introduction to Gpubox, core simulation principles, installation, and first kernel run.'
  },
  {
    slug: 'usage',
    title: 'Usage Guide',
    category: 'Guides',
    filePath: path.join(docsDir, 'USAGE.md'),
    summary: 'Comprehensive guide to memory allocation, kernel launches, stream synchronization, and cluster sizing.'
  },
  {
    slug: 'api-reference',
    title: 'API Reference',
    category: 'Reference',
    filePath: path.join(docsDir, 'API_REFERENCE.md'),
    summary: 'Complete technical reference for CudaRuntime, CudaTranspiler, GPU_PROFILES, RaceDetector, and TopologyModel.'
  },
  {
    slug: 'integration',
    title: 'Integration Guide',
    category: 'Guides',
    filePath: path.join(docsDir, 'INTEGRATION_GUIDE.md'),
    summary: 'Deploying Gpubox via CDN, bundling with Vite/Webpack, and running inside Web Workers.'
  },
  {
    slug: 'recipes',
    title: 'Recipes & Code Patterns',
    category: 'Patterns',
    filePath: path.join(docsDir, 'RECIPES.md'),
    summary: 'Verified production patterns: 2D shared tiling, warp reductions, atomic histograms, and NCCL rings.'
  },
  {
    slug: 'limitations',
    title: 'Known Limitations',
    category: 'Reference',
    filePath: path.join(docsDir, 'LIMITATIONS.md'),
    summary: 'Differences between CPU simulation and physical silicon, warp execution semantics, and unsupported CUDA syntax.'
  },
  {
    slug: 'security',
    title: 'Security & CSP Guide',
    category: 'Guides',
    filePath: path.join(docsDir, 'SECURITY_AND_CSP.md'),
    summary: 'Sandboxing untrusted user code, Content Security Policy headers, and isolated worker threads.'
  }
];

const docs = [];

for (const doc of DOC_FILES) {
  if (!fs.existsSync(doc.filePath)) {
    console.warn(`File not found: ${doc.filePath}`);
    continue;
  }
  const raw = fs.readFileSync(doc.filePath, 'utf8');
  const html = marked.parse(raw);
  docs.push({
    slug: doc.slug,
    title: doc.title,
    category: doc.category,
    summary: doc.summary,
    raw,
    html
  });
}

const outPath = path.resolve(__dirname, '../src/lib/docs-data.js');
const outContent = `// Automatically generated by scripts/build-docs-data.cjs
// Do not edit directly. Run 'node scripts/build-docs-data.cjs' to regenerate.

export const DOCS = ${JSON.stringify(docs, null, 2)};

export function getDoc(slug) {
  return DOCS.find(d => d.slug === slug) || DOCS[0];
}

export const CATEGORIES = [
  'Getting Started',
  'Guides',
  'Reference',
  'Patterns',
  'Commercial'
];
`;

fs.writeFileSync(outPath, outContent, 'utf8');
console.log(`Generated ${docs.length} documentation entries into ${outPath}`);
